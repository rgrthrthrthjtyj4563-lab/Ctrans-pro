/** 所选省份必须都被该服务商覆盖（含「全国」授权） */
export function filterAuthorizedProviders(
  auths: VarietyProviderAuth[],
  varietyName: string,
  regions: string[],
): string[] {
  if (!varietyName || regions.length === 0) return []
  const rows = auths.filter((a) => a.varietyName === varietyName)
  return [
    ...new Set(
      rows
        .filter((a) => {
          if (a.regions.includes("全国")) return true
          if (regions.includes("全国")) return a.regions.includes("全国")
          return regions.every((r) => a.regions.includes(r))
        })
        .map((a) => a.provider),
    ),
  ]
}

export function isPairAuthorized(
  auths: VarietyProviderAuth[],
  provider: string,
  varietyName: string,
  region: string,
): boolean {
  return filterAuthorizedProviders(auths, varietyName, [region]).includes(
    provider,
  )
}

/** 某服务商已授权的品种 */
export function varietiesOfProvider(
  auths: VarietyProviderAuth[],
  provider: string,
): string[] {
  return [
    ...new Set(
      auths.filter((a) => a.provider === provider).map((a) => a.varietyName),
    ),
  ]
}

/** 某服务商在所选品种上覆盖的地区（含全国） */
export function regionsOfProvider(
  auths: VarietyProviderAuth[],
  provider: string,
  varieties?: string[],
): string[] {
  const rows = auths.filter(
    (a) =>
      a.provider === provider &&
      (!varieties?.length || varieties.includes(a.varietyName)),
  )
  return [...new Set(rows.flatMap((a) => a.regions))]
}

